import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {initializeApp,deleteApp} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {getFirestore,FieldValue} from 'firebase-admin/firestore';
import {createUserService,validateAssignment} from '../../functions/src/user_service.js';
if(!process.env.FIRESTORE_EMULATOR_HOST||!process.env.FIREBASE_AUTH_EMULATOR_HOST)throw Error('Emulators required');
const app=initializeApp({projectId:'demo-hadir-kpu'},'users-test');
const auth=getAuth(app),db=getFirestore(app),initial='Demo-Hadir-123!';
const service=createUserService({auth,db,initialPassword:()=>initial,fieldValue:FieldValue});
after(()=>deleteApp(app));
const assignment={nip:'199001012020011001',name:'Pegawai Pengujian',role:'staff',departmentId:'teknis_hukum',subdepartmentId:'hukum'};
test('hierarchy rejects mismatched units and requires department-only heads',()=>{
 assert.throws(()=>validateAssignment({...assignment,subdepartmentId:'keuangan'}));
 assert.throws(()=>validateAssignment({...assignment,role:'kepala_bagian'}));
 assert.throws(()=>validateAssignment({...assignment,nip:'123'}));
 assert.equal(validateAssignment({...assignment,role:'kepala_bagian',subdepartmentId:null}).subdepartmentId,null);
});
test('admin provisions unique NIP; password gate and capabilities remain server controlled',async()=>{
 const adminRequest={auth:{uid:'provision-admin',token:{sessionVersion:'v1'}}};
 await db.doc('users/provision-admin').set({isAdmin:true,active:true,mustChangePassword:false,sessionVersion:'v1'});
 await assert.rejects(service.createManagedUser({data:assignment}),e=>e.code==='unauthenticated');
 const {uid}=await service.createManagedUser({...adminRequest,data:{...assignment,isAdmin:true,mustChangePassword:false}});
 let profile=(await db.doc(`users/${uid}`).get()).data();
 assert.equal(profile.isAdmin,false);assert.equal(profile.mustChangePassword,true);
 assert.equal((await auth.getUser(uid)).email,`${assignment.nip}@nip.hadir.invalid`);
 await assert.rejects(service.createManagedUser({...adminRequest,data:assignment}),e=>e.code==='already-exists');
 const userRequest={auth:{uid,token:{sessionVersion:profile.sessionVersion}}};
 await assert.rejects(service.createManagedUser({...userRequest,data:assignment}),e=>e.code==='failed-precondition');
 await assert.rejects(service.completeInitialPasswordChange({...userRequest,data:{password:initial}}),e=>e.code==='invalid-argument');
 await assert.rejects(service.completeInitialPasswordChange({...userRequest,data:{password:'short'}}),e=>e.code==='invalid-argument');
 const failingAuth=new Proxy(auth,{get(target,key){if(key==='revokeRefreshTokens')return async()=>{throw Error('simulated transient outage');};const value=target[key];return typeof value==='function'?value.bind(target):value;}});
 const interrupted=createUserService({auth:failingAuth,db,initialPassword:()=>initial,fieldValue:FieldValue});
 await assert.rejects(interrupted.completeInitialPasswordChange({...userRequest,data:{password:'My-New-Password-123!'}}),e=>e.code==='internal');
 assert.equal((await db.doc(`users/${uid}`).get()).data().mustChangePassword,true);
 assert.equal((await auth.getUser(uid)).customClaims.sessionVersion,userRequest.auth.token.sessionVersion);
 await service.completeInitialPasswordChange({...userRequest,data:{password:'My-New-Password-123!'}});
 profile=(await db.doc(`users/${uid}`).get()).data();
 assert.equal(profile.mustChangePassword,false);assert.notEqual(profile.sessionVersion,userRequest.auth.token.sessionVersion);
 await assert.rejects(service.createManagedUser({...userRequest,data:assignment}),e=>e.code==='permission-denied');
 const fresh={auth:{uid,token:{sessionVersion:profile.sessionVersion}}};
 await assert.rejects(service.createManagedUser({...fresh,data:assignment}),e=>e.code==='permission-denied');
 await service.updateManagedUser({...adminRequest,data:{...assignment,uid,role:'kepala_sub_bagian',isAdmin:true}});
 const updated=(await db.doc(`users/${uid}`).get()).data();
 assert.equal(updated.role,'kepala_sub_bagian');assert.equal(updated.isAdmin,false);
 const login=async password=>fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=demo-key',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:`${assignment.nip}@nip.hadir.invalid`,password,returnSecureToken:true})});
 assert.equal((await login(initial)).ok,false);assert.equal((await login('My-New-Password-123!')).ok,true);
 await auth.deleteUser(uid);
});
